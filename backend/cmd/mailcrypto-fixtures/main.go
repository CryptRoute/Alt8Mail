// Command mailcrypto-fixtures regenerates the Phase 0 interop corpus.
//
// OpenPGP fixtures are generated with the same ProtonMail/go-crypto library
// the backend will use. S/MIME fixtures are generated with the host OpenSSL
// command when it is available. Only messages are written; generated private
// keys stay in a temporary directory and are deleted.
package main

import (
	"bytes"
	"crypto"
	_ "crypto/sha256"
	"encoding/base64"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"

	"github.com/CryptRoute/Alt8Mail/backend/internal/mailcrypto"
	"github.com/ProtonMail/go-crypto/openpgp"
	"github.com/ProtonMail/go-crypto/openpgp/armor"
	"github.com/ProtonMail/go-crypto/openpgp/clearsign"
	"github.com/ProtonMail/go-crypto/openpgp/packet"
)

type fixtureExpectation struct {
	Name        string              `json:"name"`
	Protocol    mailcrypto.Protocol `json:"protocol"`
	Encrypted   bool                `json:"encrypted"`
	Signed      bool                `json:"signed"`
	Kind        mailcrypto.Kind     `json:"kind"`
	Description string              `json:"description"`
}

func main() {
	out := flag.String("out", filepath.Join("internal", "mailcrypto", "testdata", "fixtures"), "fixture output directory")
	flag.Parse()
	if err := run(*out); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(outDir string) error {
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		return err
	}
	tempDir, err := os.MkdirTemp("", "a8m-mailcrypto-fixtures-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(tempDir)

	body := []byte("Alt8Mail Phase 0 interop fixture.\r\nThis body is used only by tests.\r\n")
	bodyPath := filepath.Join(tempDir, "body.txt")
	if err := os.WriteFile(bodyPath, body, 0o600); err != nil {
		return err
	}

	expectations := []fixtureExpectation{}
	add := func(name string, data []byte, expect fixtureExpectation) error {
		// Do not normalize signed or encrypted bytes here: S/MIME digests cover
		// the exact entity OpenSSL produced, including its CRLF quirks.
		if err := os.WriteFile(filepath.Join(outDir, name), data, 0o644); err != nil {
			return err
		}
		expect.Name = name
		expectations = append(expectations, expect)
		return nil
	}

	if err := generateSMIME(tempDir, bodyPath, add); err != nil {
		fmt.Fprintf(os.Stderr, "S/MIME fixtures skipped: %v\n", err)
	}
	if err := generatePGP(tempDir, body, add); err != nil {
		return err
	}
	plain := buildPlainFixture()
	if err := add("plain.eml", plain, fixtureExpectation{Description: "ordinary multipart/alternative message"}); err != nil {
		return err
	}
	malformed := buildMalformedSignedFixture()
	if err := add("malformed-signed.eml", malformed, fixtureExpectation{Kind: mailcrypto.KindMalformed, Description: "multipart/signed with no signature part"}); err != nil {
		return err
	}
	manifest, err := json.MarshalIndent(map[string]any{
		"generatedBy": "go run ./cmd/mailcrypto-fixtures",
		"fixtures":    expectations,
	}, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(outDir, "fixtures.json"), append(manifest, '\n'), 0o644)
}

func generateSMIME(tempDir, bodyPath string, add func(string, []byte, fixtureExpectation) error) error {
	if _, err := exec.LookPath("openssl"); err != nil {
		return err
	}
	keyPath := filepath.Join(tempDir, "smime.key")
	certPath := filepath.Join(tempDir, "smime.crt")
	if err := runCommand("openssl", "req", "-x509", "-newkey", "rsa:2048", "-nodes",
		"-keyout", keyPath, "-out", certPath, "-days", "3650",
		"-subj", "/CN=Alt8Mail Test Sender/emailAddress=sender@example.test",
		"-addext", "subjectAltName=email:sender@example.test",
		"-addext", "keyUsage=digitalSignature,keyEncipherment",
		"-addext", "extendedKeyUsage=emailProtection"); err != nil {
		return err
	}
	signedPath := filepath.Join(tempDir, "smime-signed.mime")
	if err := runCommand("openssl", "smime", "-sign", "-in", bodyPath, "-signer", certPath,
		"-inkey", keyPath, "-outform", "SMIME", "-md", "sha256", "-out", signedPath); err != nil {
		return err
	}
	signed, err := os.ReadFile(signedPath)
	if err != nil {
		return err
	}
	if err := add("smime-signed.eml", withHeaders("S/MIME signed fixture", signed), fixtureExpectation{
		Protocol: mailcrypto.ProtocolSMIME, Signed: true, Kind: mailcrypto.KindSMIMESigned,
		Description: "multipart/signed S/MIME message generated by OpenSSL",
	}); err != nil {
		return err
	}

	encryptedPath := filepath.Join(tempDir, "smime-enveloped.mime")
	if err := runCommand("openssl", "smime", "-encrypt", "-in", bodyPath, "-outform", "SMIME",
		"-aes256", "-out", encryptedPath, certPath); err != nil {
		return err
	}
	encrypted, err := os.ReadFile(encryptedPath)
	if err != nil {
		return err
	}
	if err := add("smime-enveloped.eml", withHeaders("S/MIME enveloped fixture", encrypted), fixtureExpectation{
		Protocol: mailcrypto.ProtocolSMIME, Encrypted: true, Kind: mailcrypto.KindSMIMEEnveloped,
		Description: "application/pkcs7-mime enveloped-data generated by OpenSSL",
	}); err != nil {
		return err
	}

	signThenEncryptPath := filepath.Join(tempDir, "smime-sign-then-encrypt.mime")
	if err := runCommand("openssl", "smime", "-encrypt", "-in", signedPath, "-outform", "SMIME",
		"-aes256", "-out", signThenEncryptPath, certPath); err != nil {
		return err
	}
	signThenEncrypt, err := os.ReadFile(signThenEncryptPath)
	if err != nil {
		return err
	}
	return add("smime-sign-then-encrypt.eml", withHeaders("S/MIME sign-then-encrypt fixture", signThenEncrypt), fixtureExpectation{
		Protocol: mailcrypto.ProtocolSMIME, Encrypted: true, Kind: mailcrypto.KindSMIMEEnveloped,
		Description: "signed S/MIME entity encrypted as enveloped-data",
	})
}

func generatePGP(tempDir string, body []byte, add func(string, []byte, fixtureExpectation) error) error {
	config := &packet.Config{
		RSABits:     2048,
		DefaultHash: crypto.SHA256,
		Time:        func() time.Time { return time.Date(2026, 11, 15, 0, 0, 0, 0, time.UTC) },
	}
	entity, err := openpgp.NewEntity("Alt8Mail Test Sender", "", "sender@example.test", config)
	if err != nil {
		return err
	}
	publicKey, err := armoredPublicKey(entity)
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(tempDir, "pgp-public.asc"), publicKey, 0o600); err != nil {
		return err
	}

	encrypted, err := encryptPGP(entity, body)
	if err != nil {
		return err
	}
	pgpMIME := buildPGPMIMEEncrypted(encrypted)
	if err := add("pgp-mime-encrypted.eml", pgpMIME, fixtureExpectation{
		Protocol: mailcrypto.ProtocolOpenPGP, Encrypted: true, Kind: mailcrypto.KindPGPMIMEEncrypted,
		Description: "multipart/encrypted PGP/MIME message",
	}); err != nil {
		return err
	}

	signedEntity := append([]byte("Content-Type: text/plain; charset=UTF-8\r\n\r\n"), body...)
	detached, err := detachedPGPSignature(entity, signedEntity)
	if err != nil {
		return err
	}
	pgpSigned := buildPGPMIMESigned(signedEntity, detached)
	if err := add("pgp-mime-signed.eml", pgpSigned, fixtureExpectation{
		Protocol: mailcrypto.ProtocolOpenPGP, Signed: true, Kind: mailcrypto.KindPGPMIMESigned,
		Description: "multipart/signed PGP/MIME message",
	}); err != nil {
		return err
	}

	inlineEncrypted := buildInlineEncrypted(encrypted)
	if err := add("pgp-inline-encrypted.eml", inlineEncrypted, fixtureExpectation{
		Protocol: mailcrypto.ProtocolOpenPGP, Encrypted: true, Kind: mailcrypto.KindPGPInlineEncrypted,
		Description: "legacy inline armored PGP message",
	}); err != nil {
		return err
	}

	clearSigned, err := clearSignPGP(entity, body)
	if err != nil {
		return err
	}
	inlineSigned := buildInlineSigned(clearSigned)
	if err := add("pgp-inline-signed.eml", inlineSigned, fixtureExpectation{
		Protocol: mailcrypto.ProtocolOpenPGP, Signed: true, Kind: mailcrypto.KindPGPInlineSigned,
		Description: "legacy inline clear-signed PGP message",
	}); err != nil {
		return err
	}

	keyBlock := buildPGPKeyBlock(publicKey)
	return add("pgp-key-block.eml", keyBlock, fixtureExpectation{
		Description: "message carrying a PGP public key block, not protected mail",
	})
}

func runCommand(name string, args ...string) error {
	command := exec.Command(name, args...)
	command.Stdout = ioDiscard{}
	command.Stderr = ioDiscard{}
	if err := command.Run(); err != nil {
		return fmt.Errorf("%s %s: %w", name, strings.Join(args, " "), err)
	}
	return nil
}

type ioDiscard struct{}

func (ioDiscard) Write(p []byte) (int, error) { return len(p), nil }

func withHeaders(subject string, entity []byte) []byte {
	var buffer bytes.Buffer
	buffer.WriteString("From: Alt8Mail Test Sender <sender@example.test>\r\n")
	buffer.WriteString("To: Alt8Mail Test Recipient <recipient@example.test>\r\n")
	buffer.WriteString("Subject: " + subject + "\r\n")
	buffer.WriteString("Date: Sun, 15 Nov 2026 00:00:00 +0000\r\n")
	buffer.WriteString("Message-ID: <" + fixtureID(subject) + "@example.test>\r\n")
	buffer.WriteString("X-Alt8Mail-Fixture: phase0\r\n")
	buffer.Write(entity)
	return buffer.Bytes()
}

func fixtureID(value string) string {
	var buffer strings.Builder
	for _, char := range strings.ToLower(value) {
		if (char >= 'a' && char <= 'z') || (char >= '0' && char <= '9') {
			buffer.WriteRune(char)
		} else if buffer.Len() > 0 {
			buffer.WriteByte('-')
		}
	}
	return strings.Trim(buffer.String(), "-")
}

func armoredPublicKey(entity *openpgp.Entity) ([]byte, error) {
	var buffer bytes.Buffer
	writer, err := armor.Encode(&buffer, "PGP PUBLIC KEY BLOCK", nil)
	if err != nil {
		return nil, err
	}
	if err := entity.Serialize(writer); err != nil {
		return nil, err
	}
	if err := writer.Close(); err != nil {
		return nil, err
	}
	return buffer.Bytes(), nil
}

func encryptPGP(entity *openpgp.Entity, body []byte) ([]byte, error) {
	var buffer bytes.Buffer
	writer, err := openpgp.Encrypt(&buffer, []*openpgp.Entity{entity}, nil, nil, nil)
	if err != nil {
		return nil, err
	}
	if _, err := writer.Write(body); err != nil {
		return nil, err
	}
	if err := writer.Close(); err != nil {
		return nil, err
	}
	return buffer.Bytes(), nil
}

func detachedPGPSignature(entity *openpgp.Entity, body []byte) ([]byte, error) {
	var buffer bytes.Buffer
	if err := openpgp.ArmoredDetachSign(&buffer, entity, bytes.NewReader(body), nil); err != nil {
		return nil, err
	}
	return buffer.Bytes(), nil
}

func clearSignPGP(entity *openpgp.Entity, body []byte) ([]byte, error) {
	var buffer bytes.Buffer
	writer, err := clearsign.Encode(&buffer, entity.PrivateKey, nil)
	if err != nil {
		return nil, err
	}
	if _, err := writer.Write(body); err != nil {
		return nil, err
	}
	if err := writer.Close(); err != nil {
		return nil, err
	}
	return buffer.Bytes(), nil
}

func buildPGPMIMEEncrypted(ciphertext []byte) []byte {
	boundary := "alt8mail-pgp-encrypted"
	var buffer bytes.Buffer
	buffer.WriteString("From: Alt8Mail Test Sender <sender@example.test>\r\n")
	buffer.WriteString("To: Alt8Mail Test Recipient <recipient@example.test>\r\n")
	buffer.WriteString("Subject: PGP/MIME encrypted fixture\r\n")
	buffer.WriteString("Date: Sun, 15 Nov 2026 00:00:00 +0000\r\n")
	buffer.WriteString("Message-ID: <pgp-mime-encrypted@example.test>\r\n")
	buffer.WriteString("X-Alt8Mail-Fixture: phase0\r\n")
	buffer.WriteString("MIME-Version: 1.0\r\n")
	buffer.WriteString(`Content-Type: multipart/encrypted; protocol="application/pgp-encrypted"; boundary="` + boundary + `"` + "\r\n")
	buffer.WriteString("\r\n")
	buffer.WriteString("--" + boundary + "\r\n")
	buffer.WriteString("Content-Type: application/pgp-encrypted\r\n")
	buffer.WriteString("\r\n")
	buffer.WriteString("Version: 1\r\n")
	buffer.WriteString("--" + boundary + "\r\n")
	buffer.WriteString("Content-Type: application/octet-stream; name=\"encrypted.asc\"\r\n")
	buffer.WriteString("Content-Disposition: inline; filename=\"encrypted.asc\"\r\n")
	buffer.WriteString("Content-Transfer-Encoding: base64\r\n")
	buffer.WriteString("\r\n")
	buffer.WriteString(base64Lines(ciphertext))
	buffer.WriteString("\r\n--" + boundary + "--\r\n")
	return buffer.Bytes()
}

func buildPGPMIMESigned(signedEntity, signature []byte) []byte {
	boundary := "alt8mail-pgp-signed"
	var buffer bytes.Buffer
	buffer.WriteString("From: Alt8Mail Test Sender <sender@example.test>\r\n")
	buffer.WriteString("To: Alt8Mail Test Recipient <recipient@example.test>\r\n")
	buffer.WriteString("Subject: PGP/MIME signed fixture\r\n")
	buffer.WriteString("Date: Sun, 15 Nov 2026 00:00:00 +0000\r\n")
	buffer.WriteString("Message-ID: <pgp-mime-signed@example.test>\r\n")
	buffer.WriteString("X-Alt8Mail-Fixture: phase0\r\n")
	buffer.WriteString("MIME-Version: 1.0\r\n")
	buffer.WriteString(`Content-Type: multipart/signed; protocol="application/pgp-signature"; micalg=pgp-sha256; boundary="` + boundary + `"` + "\r\n")
	buffer.WriteString("\r\n")
	buffer.WriteString("--" + boundary + "\r\n")
	buffer.Write(signedEntity)
	buffer.WriteString("\r\n--" + boundary + "\r\n")
	buffer.WriteString("Content-Type: application/pgp-signature; name=\"signature.asc\"\r\n")
	buffer.WriteString("Content-Disposition: attachment; filename=\"signature.asc\"\r\n")
	buffer.WriteString("\r\n")
	buffer.Write(signature)
	buffer.WriteString("\r\n--" + boundary + "--\r\n")
	return buffer.Bytes()
}

func buildInlineEncrypted(ciphertext []byte) []byte {
	var armored bytes.Buffer
	writer, _ := armor.Encode(&armored, "PGP MESSAGE", nil)
	_, _ = writer.Write(ciphertext)
	_ = writer.Close()
	var buffer bytes.Buffer
	buffer.WriteString("From: Alt8Mail Test Sender <sender@example.test>\r\n")
	buffer.WriteString("To: Alt8Mail Test Recipient <recipient@example.test>\r\n")
	buffer.WriteString("Subject: Inline PGP encrypted fixture\r\n")
	buffer.WriteString("Date: Sun, 15 Nov 2026 00:00:00 +0000\r\n")
	buffer.WriteString("Message-ID: <pgp-inline-encrypted@example.test>\r\n")
	buffer.WriteString("X-Alt8Mail-Fixture: phase0\r\n")
	buffer.WriteString("MIME-Version: 1.0\r\n")
	buffer.WriteString("Content-Type: text/plain; charset=UTF-8\r\n")
	buffer.WriteString("Content-Transfer-Encoding: 7bit\r\n")
	buffer.WriteString("\r\n")
	buffer.Write(armored.Bytes())
	return buffer.Bytes()
}

