func buildMalformedSignedFixture() []byte {
	var buffer bytes.Buffer
	buffer.WriteString("From: Alt8Mail Test Sender <sender@example.test>\r\n")
	buffer.WriteString("To: Alt8Mail Test Recipient <recipient@example.test>\r\n")
	buffer.WriteString("Subject: Broken multipart/signed fixture\r\n")
	buffer.WriteString("Message-ID: <malformed-signed@example.test>\r\n")
	buffer.WriteString("MIME-Version: 1.0\r\n")
	buffer.WriteString(`Content-Type: multipart/signed; protocol="application/pgp-signature"; boundary="broken"` + "\r\n")
	buffer.WriteString("\r\n--broken\r\nContent-Type: text/plain\r\n\r\nOnly one part.\r\n")
	return buffer.Bytes()
}

func base64Lines(data []byte) string {
	encoded := base64.StdEncoding.EncodeToString(data)
	var buffer bytes.Buffer
	for len(encoded) > 76 {
		buffer.WriteString(encoded[:76] + "\r\n")
		encoded = encoded[76:]
	}
	buffer.WriteString(encoded)
	return buffer.String()
}
